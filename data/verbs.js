// Full conjugation tables for the most useful verbs. Every form is written out (no guessing),
// except "would have" (past + volna), which is built from the past tense.
// Person order: én, te, ő, mi, ti, ők.  Commands (imp): te, ön, mi, ti.  should (subj): én, ő, ők.
// Alternatives: "menj/menjél".
// English: en = 'base|3rd person|past|past participle' (participle only where "would have" is drilled).
// Optional e: { d: definite parts, c: conditional, cd: conditional definite, i: command base,
//   id: definite command, l: "-lak" sentence, s: "should I…" base, k: "have to…" base,
//   pc / pcd: "would have…" phrases, x: { paradigm: [exact English for each person] } }

